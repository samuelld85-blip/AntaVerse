export type QuestionCategory = string;

export interface Question {
  id: string;
  category: QuestionCategory;
  themeId: string;
  prompt: string;
  answer: number;
  unit: string;
  sourceLabel: string;
  sourceUrl: string;
  note?: string;
}

type Seed = readonly [id: string, prompt: string, answer: number, unit: string, note?: string];

interface ThemeDefinition {
  id: string;
  label: string;
  sourceLabel: string;
  sourceUrl: string;
  questions: readonly Seed[];
}

const theme = (definition: ThemeDefinition): readonly Question[] =>
  definition.questions.map(([id, prompt, answer, unit, note]) => ({
    id,
    category: definition.label,
    themeId: definition.id,
    prompt,
    answer,
    unit,
    sourceLabel: definition.sourceLabel,
    sourceUrl: definition.sourceUrl,
    ...(note ? { note } : {}),
  }));

