function slugify(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-|-$/gu, "");
}

export const cards: readonly Card[] = groups.flatMap((group) =>
  group.items.map(([word, specific]) => ({
    id: slugify(word),
    word,
    forbidden: [specific, ...group.clues] as [string, string, string],
  })),
);
