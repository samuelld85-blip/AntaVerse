// Country reference points used for the search bar and for scoring distance.
// `id` is the ISO 3166-1 numeric code as a zero-padded string — it matches
// `feature.id` in world-atlas's countries-110m topojson (see world-topology.ts),
// so a country picked from search can be matched back to its map shape.
// `lat`/`lon` are the approximate coordinates of the capital (a few countries
// use the de facto seat of government or largest city where that is clearly
// more representative). Precision is "right region", not survey-grade: the
// scoring bands in lib/game/distance.ts are hundreds of km wide, so being off
// by a few km never changes a score.
//
// Antarctica and the three territories with no ISO numeric code in the map
// dataset (Northern Cyprus, Somaliland, Kosovo) are intentionally omitted —
// they exist on the rendered map (see world-topology.ts) but are not
// selectable answers here.
